#!/usr/bin/env bash
# Renders the runtime .env consumed by docker compose.
#
#   bash deploy/render-env.sh                     # write ./.env from the environment
#   bash deploy/render-env.sh --out .env.deploy   # write somewhere else
#   bash deploy/render-env.sh --check             # validate only, write nothing
#   bash deploy/render-env.sh < secrets.env       # KEY=VALUE from stdin wins
#
# In CI the values come from GitHub Actions Secrets and Variables; on a server
# they can be exported first. Values are never echoed and the output file is
# created with mode 600 so it can sit next to docker-compose.yml safely.
set -euo pipefail

out=.env
check_only=0

while [ $# -gt 0 ]; do
  case "$1" in
    --out)
      [ $# -ge 2 ] || { printf -- '--out needs a path\n' >&2; exit 2; }
      out=$2
      shift 2
      ;;
    --check)
      check_only=1
      shift
      ;;
    -h | --help)
      sed -n '2,10p' "$0"
      exit 0
      ;;
    *)
      printf 'Unknown argument: %s\n' "$1" >&2
      exit 2
      ;;
  esac
done

# Optional KEY=VALUE input on stdin. It takes precedence over the environment
# so a deployment can stream a file over SSH without exporting anything.
declare -A piped=()
if [ ! -t 0 ]; then
  while IFS= read -r line || [ -n "$line" ]; do
    case "$line" in
      '' | '#'*) continue ;;
    esac
    key=${line%%=*}
    value=${line#*=}
    [ "$value" = "$line" ] && continue
    if ! [[ $key =~ ^[A-Z_][A-Z0-9_]*$ ]]; then
      printf 'Invalid variable name on stdin: %s\n' "$key" >&2
      exit 2
    fi
    # Strip one layer of matching quotes, as docker compose's env_file does.
    if [[ $value == \"*\" && $value == *\" ]] || [[ $value == \'*\' && $value == *\' ]]; then
      value=${value:1:${#value}-2}
    fi
    piped[$key]=$value
  done
fi

value_of() {
  local key=$1 ref=$1
  if [ -n "${piped[$key]+set}" ]; then
    printf '%s' "${piped[$key]}"
  else
    printf '%s' "${!ref-}"
  fi
}

# Percent-encode a value for the userinfo part of a URL. Passwords are routinely
# generated with @ : / # which would otherwise be read as URL delimiters.
urlencode() {
  local s=$1 encoded= i c
  for ((i = 0; i < ${#s}; i++)); do
    c=${s:i:1}
    case $c in
      [A-Za-z0-9.~_-]) encoded+=$c ;;
      *) printf -v c '%%%02X' "'$c" && encoded+=$c ;;
    esac
  done
  printf '%s' "$encoded"
}

required_values=(
  JWT_ACCESS_SECRET
  JWT_REFRESH_SECRET
  MYSQL_PASSWORD
  MYSQL_ROOT_PASSWORD
  ADMIN_PASSWORD
  PAYPAL_CLIENT_ID
  PAYPAL_CLIENT_SECRET
  PAYPAL_WEBHOOK_ID
)

missing=()
for key in "${required_values[@]}"; do
  if [ -z "$(value_of "$key")" ]; then
    missing+=("$key")
  fi
done

if [ ${#missing[@]} -gt 0 ]; then
  printf 'Missing required values: %s\n' "${missing[*]}" >&2
  printf 'Set them as GitHub Actions Secrets (or export them before running this script).\n' >&2
  exit 1
fi

public_base_url=$(value_of PUBLIC_BASE_URL)
public_base_url=${public_base_url:-https://formotax.ecommica.com}
public_base_url=${public_base_url%/}

web_port=$(value_of WEB_PORT)
web_port=${web_port:-3004}

api_port=$(value_of API_PORT)
api_port=${api_port:-8083}

mysql_database=$(value_of MYSQL_DATABASE)
mysql_database=${mysql_database:-tax_form}

mysql_user=$(value_of MYSQL_USER)
mysql_user=${mysql_user:-tax}

mysql_port=$(value_of MYSQL_PORT)
mysql_port=${mysql_port:-3306}

redis_port=$(value_of REDIS_PORT)
redis_port=${redis_port:-6379}

# docker-compose.prod.yml consumes DATABASE_URL directly so the password can be
# escaped here. An explicitly supplied DATABASE_URL still wins.
database_url=$(value_of DATABASE_URL)
if [ -z "$database_url" ]; then
  database_url="mysql://${mysql_user}:$(urlencode "$(value_of MYSQL_PASSWORD)")@mysql:${mysql_port}/${mysql_database}"
fi

jwt_access_ttl=$(value_of JWT_ACCESS_TTL)
jwt_access_ttl=${jwt_access_ttl:-900}

jwt_refresh_ttl=$(value_of JWT_REFRESH_TTL)
jwt_refresh_ttl=${jwt_refresh_ttl:-2592000}

cors_origins=$(value_of CORS_ORIGINS)
cors_origins=${cors_origins:-$public_base_url}

download_price=$(value_of DOWNLOAD_PRICE_USD)
download_price=${download_price:-1}

access_hours=$(value_of DOWNLOAD_ACCESS_HOURS)
access_hours=${access_hours:-24}

admin_email=$(value_of ADMIN_EMAIL)
admin_email=${admin_email:-admin@formotax.com}

paypal_mode=$(value_of PAYPAL_MODE)
paypal_mode=${paypal_mode:-sandbox}

paypal_brand=$(value_of PAYPAL_BRAND_NAME)
paypal_brand=${paypal_brand:-FormoTax}

if [ "$check_only" -eq 1 ]; then
  printf 'Configuration looks complete; nothing was written.\n'
  exit 0
fi

umask 077
tmp=$(mktemp "${out}.XXXXXX")
cleanup() { rm -f "$tmp"; }
trap cleanup EXIT

cat >"$tmp" <<EOF
# Generated by deploy/render-env.sh at $(date -u +%Y-%m-%dT%H:%M:%SZ)
# Contains credentials: never commit this file.

# ---------- Web ----------
NEXT_PUBLIC_SITE_URL=$public_base_url
NEXT_PUBLIC_API_URL=$public_base_url/api/v1

# ---------- API ----------
NODE_ENV=production
PORT=4000
WEB_URL=$public_base_url
REDIS_URL=redis://localhost:$redis_port
CORS_ORIGINS=$cors_origins
JWT_ACCESS_SECRET=$(value_of JWT_ACCESS_SECRET)
JWT_ACCESS_TTL=$jwt_access_ttl
JWT_REFRESH_SECRET=$(value_of JWT_REFRESH_SECRET)
JWT_REFRESH_TTL=$jwt_refresh_ttl

# ---------- Pay-per-download ----------
DOWNLOAD_PRICE_USD=$download_price
DOWNLOAD_ACCESS_HOURS=$access_hours

# ---------- Admin ----------
ADMIN_EMAIL=$admin_email
ADMIN_PASSWORD=$(value_of ADMIN_PASSWORD)

# ---------- Docker Compose ----------
PUBLIC_BASE_URL=$public_base_url
WEB_PORT=$web_port
API_PORT=$api_port
MYSQL_DATABASE=$mysql_database
MYSQL_USER=$mysql_user
MYSQL_PASSWORD=$(value_of MYSQL_PASSWORD)
MYSQL_ROOT_PASSWORD=$(value_of MYSQL_ROOT_PASSWORD)
MYSQL_PORT=$mysql_port
REDIS_PORT=$redis_port
DATABASE_URL=$database_url

# ---------- PayPal (the only payment method) ----------
PAYPAL_MODE=$paypal_mode
PAYPAL_CLIENT_ID=$(value_of PAYPAL_CLIENT_ID)
PAYPAL_CLIENT_SECRET=$(value_of PAYPAL_CLIENT_SECRET)
PAYPAL_WEBHOOK_ID=$(value_of PAYPAL_WEBHOOK_ID)
PAYPAL_BRAND_NAME=$paypal_brand
PAYPAL_API_URL=$(value_of PAYPAL_API_URL)
EOF

chmod 600 "$tmp"
mv "$tmp" "$out"
trap - EXIT

printf 'Wrote %s with %s variables (mode 600).\n' "$out" "$(grep -c '^[A-Z]' "$out")"
